create or replace function public.rms_is_staff_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role in ('admin','staff')
  );
$$;

revoke all on function public.rms_is_staff_admin() from public;
grant execute on function public.rms_is_staff_admin() to anon, authenticated;

