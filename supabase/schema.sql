create or replace function public.rms_request(p_path text, p_body jsonb default '{}'::jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_profile public.profiles%rowtype;
  v_role text;
  v_path text := split_part(p_path, '?', 1);
  v_query text := split_part(p_path, '?', 2);
  v_menu jsonb;
  v_tables jsonb;
  v_orders jsonb;
  v_order public.orders%rowtype;
  v_bill public.bills%rowtype;
  v_res public.reservations%rowtype;
  v_item public.menu%rowtype;
  v_table public.dining_tables%rowtype;
  v_settings jsonb;
  v_items jsonb;
  v_result jsonb;
  v_table_id bigint;
  v_menu_id bigint;
  v_qty integer;
  v_total_items integer;
  v_discount_pct numeric;
  v_subtotal numeric(12,2);
  v_discount numeric(12,2);
  v_gst numeric(12,2);
  v_total numeric(12,2);
  v_date date;
  v_time time;
  v_guests integer;
  v_name text;
  v_phone text;
  v_method text;
  v_csv text;
  v_row record;
begin
  if v_uid is null then
    raise exception 'Please sign in';
  end if;
  select * into v_profile from public.profiles where id = v_uid;
  if not found then
    raise exception 'Account profile not found. Contact the restaurant administrator.';
  end if;
  v_role := v_profile.role;

  if v_path = '/me' then
    return jsonb_build_object('user', v_profile.username, 'email', v_profile.email, 'role', v_role, 'gst_rate', 5,
      'restaurant', coalesce((select settings ->> 'restaurant' from public.storefront where id), 'Restaurant'),
      'address', '', 'phone', '', 'gstin', '');
  end if;

  if v_path = '/storefront' and p_body = '{}'::jsonb then
    return coalesce((select settings from public.storefront where id), '{}'::jsonb);
  end if;

  if v_path = '/menu' and p_body = '{}'::jsonb then
    select coalesce(jsonb_agg(jsonb_build_object(
      'id', id, 'name', name, 'category', category, 'price', price, 'available', available
    ) order by category, id), '[]'::jsonb)
    into v_menu from public.menu where v_role <> 'customer' or available;
    return v_menu;
  end if;

  if v_path = '/tables' and p_body = '{}'::jsonb then
    select coalesce(jsonb_agg(jsonb_build_object('id', t.id, 'seats', t.seats, 'status', t.status) order by t.id), '[]'::jsonb)
    into v_tables
    from public.dining_tables t
    where v_role <> 'customer' or t.status = 'Free' or exists (
      select 1 from public.orders o where o.table_id = t.id and o.status = 'Open' and o.user_id = v_uid
    );
    return v_tables;
  end if;

  if v_path = '/orders' and p_body = '{}'::jsonb then
    select coalesce(jsonb_agg(jsonb_build_object(
      'id', o.id,
      'table_id', o.table_id,
      'created', to_char(o.created_at, 'YYYY-MM-DD HH24:MI:SS'),
      'taken_by', o.taken_by,
      'items', coalesce((
        select jsonb_agg(jsonb_build_object('menu_id', oi.menu_id, 'name', oi.name, 'qty', oi.qty,
          'price', oi.price, 'amount', round(oi.qty * oi.price, 2)) order by oi.id)
        from public.order_items oi where oi.order_id = o.id
      ), '[]'::jsonb),
      'subtotal', coalesce((select sum(oi.qty * oi.price) from public.order_items oi where oi.order_id = o.id), 0)
    ) order by o.created_at), '[]'::jsonb)
    into v_orders from public.orders o
    where o.status = 'Open' and (v_role <> 'customer' or o.user_id = v_uid);
    return v_orders;
  end if;

  if v_path = '/storefront' and p_body <> '{}'::jsonb then
    if v_role <> 'admin' then raise exception 'Admin access required'; end if;
    if length(btrim(coalesce(p_body ->> 'restaurant', ''))) not between 1 and 60
      or length(btrim(coalesce(p_body ->> 'banner_kicker', ''))) not between 1 and 50
      or length(btrim(coalesce(p_body ->> 'banner_title', ''))) not between 1 and 100
      or length(btrim(coalesce(p_body ->> 'banner_subtitle', ''))) > 240 then
      raise exception 'Check storefront text lengths';
    end if;
    if jsonb_typeof(p_body -> 'colors') <> 'object' then raise exception 'Choose all storefront colors'; end if;
    for v_name in select unnest(array['background','surface','header','banner','primary','heading','text']) loop
      if coalesce(p_body #>> array['colors', v_name], '') !~ '^#[0-9a-fA-F]{6}$' then
        raise exception 'Invalid color: %', v_name;
      end if;
    end loop;
    update public.storefront set settings = settings || jsonb_build_object(
      'restaurant', btrim(p_body ->> 'restaurant'),
      'banner_kicker', btrim(p_body ->> 'banner_kicker'),
      'banner_title', btrim(p_body ->> 'banner_title'),
      'banner_subtitle', btrim(p_body ->> 'banner_subtitle'),
      'colors', p_body -> 'colors'
    ) where id returning settings into v_settings;
    return v_settings;
  end if;

  if v_path = '/storefront/image' then
    if v_role <> 'admin' then raise exception 'Admin access required'; end if;
    if coalesce(p_body ->> 'kind', '') not in ('banner','logo','menu') then raise exception 'Unknown image type'; end if;
    if coalesce(p_body ->> 'path', '') !~ '^[a-zA-Z0-9-]{36}\.(jpg|png|webp)$' then raise exception 'Invalid image path'; end if;
    if p_body ->> 'kind' = 'menu' then
      v_menu_id := (p_body ->> 'menu_id')::bigint;
      if not exists (select 1 from public.menu where id = v_menu_id) then raise exception 'Menu item not found'; end if;
      update public.storefront set settings = jsonb_set(settings, array['menu_images', v_menu_id::text], to_jsonb('/uploads/' || (p_body ->> 'path')), true)
        where id returning settings into v_settings;
    else
      update public.storefront set settings = jsonb_set(settings, array[(p_body ->> 'kind') || '_image'], to_jsonb('/uploads/' || (p_body ->> 'path')), true)
        where id returning settings into v_settings;
    end if;
    return v_settings;
  end if;

  if v_path = '/storefront/image/remove' then
    if v_role <> 'admin' then raise exception 'Admin access required'; end if;
    if p_body ->> 'kind' = 'menu' then
      v_menu_id := (p_body ->> 'menu_id')::bigint;
      update public.storefront set settings = jsonb_set(settings, '{menu_images}', coalesce(settings -> 'menu_images', '{}'::jsonb) - v_menu_id::text, true)
        where id returning settings into v_settings;
    elsif p_body ->> 'kind' in ('banner','logo') then
      update public.storefront set settings = jsonb_set(settings, array[(p_body ->> 'kind') || '_image'], '""'::jsonb, true)
        where id returning settings into v_settings;
    else
      raise exception 'Unknown image type';
    end if;
    return v_settings;
  end if;

  if v_path = '/password' then
    raise exception 'Use the signed-in account password update';
  end if;

  if v_path = '/menu' and p_body <> '{}'::jsonb then
    if v_role <> 'admin' then raise exception 'Admin access required'; end if;
    v_name := btrim(coalesce(p_body ->> 'name', ''));
    if length(v_name) not between 1 and 60 then raise exception 'Name must be 1-60 characters'; end if;
    if length(btrim(coalesce(p_body ->> 'category', ''))) not between 1 and 30 then raise exception 'Category must be 1-30 characters'; end if;
    if (p_body ->> 'price')::numeric not between 0.01 and 100000 then raise exception 'Price must be greater than 0 and at most 100000'; end if;
    insert into public.menu(name, category, price)
      values (v_name, btrim(p_body ->> 'category'), (p_body ->> 'price')::numeric);
    return jsonb_build_object('ok', true);
  end if;

  if v_path in ('/menu/update','/menu/toggle','/menu/delete') then
    if v_role <> 'admin' then raise exception 'Admin access required'; end if;
    v_menu_id := (p_body ->> 'id')::bigint;
    if v_path = '/menu/update' then
      v_name := btrim(coalesce(p_body ->> 'name', ''));
      if length(v_name) not between 1 and 60 or length(btrim(coalesce(p_body ->> 'category', ''))) not between 1 and 30 then
        raise exception 'Check item name and category';
      end if;
      update public.menu set name = v_name, category = btrim(p_body ->> 'category'), price = (p_body ->> 'price')::numeric
        where id = v_menu_id;
      if not found then raise exception 'Menu item not found'; end if;
    elsif v_path = '/menu/toggle' then
      update public.menu set available = not available where id = v_menu_id;
      if not found then raise exception 'Menu item not found'; end if;
    else
      if exists (select 1 from public.order_items where menu_id = v_menu_id) then
        raise exception 'This item has sales history. Hide it instead of deleting.';
      end if;
      delete from public.menu where id = v_menu_id;
      if not found then raise exception 'Menu item not found'; end if;
      update public.storefront set settings = jsonb_set(settings, '{menu_images}', coalesce(settings -> 'menu_images', '{}'::jsonb) - v_menu_id::text, true) where id;
    end if;
    return jsonb_build_object('ok', true);
  end if;

  if v_path = '/tables/add' then
    if v_role <> 'admin' then raise exception 'Admin access required'; end if;
    v_guests := (p_body ->> 'seats')::integer;
    if v_guests not between 1 and 30 then raise exception 'Seats must be between 1 and 30'; end if;
    insert into public.dining_tables(seats) values (v_guests) returning id into v_table_id;
    return jsonb_build_object('id', v_table_id);
  end if;

  if v_path = '/tables/delete' then
    if v_role <> 'admin' then raise exception 'Admin access required'; end if;
    v_table_id := (p_body ->> 'id')::bigint;
    if not exists (select 1 from public.dining_tables where id = v_table_id) then raise exception 'No such table'; end if;
    if exists (select 1 from public.orders where table_id = v_table_id)
      or exists (select 1 from public.reservations where table_id = v_table_id) then
      raise exception 'This table has order or reservation history and cannot be deleted';
    end if;
    delete from public.dining_tables where id = v_table_id;
    return jsonb_build_object('ok', true);
  end if;

  if v_path in ('/orders/add','/orders/remove','/orders/cancel') then
    v_table_id := (p_body ->> 'table_id')::bigint;
    perform pg_advisory_xact_lock(v_table_id);
    select * into v_table from public.dining_tables where id = v_table_id for update;
    if not found then raise exception 'No such table'; end if;
    select * into v_order from public.orders where table_id = v_table_id and status = 'Open' for update;
    if v_path = '/orders/add' then
      v_menu_id := (p_body ->> 'menu_id')::bigint;
      v_qty := (p_body ->> 'qty')::integer;
      if v_qty not between 1 and 50 then raise exception 'Quantity must be between 1 and 50'; end if;
      select * into v_item from public.menu where id = v_menu_id and available;
      if not found then raise exception 'Item unavailable'; end if;
      if v_role = 'customer' and found and v_order.id is not null and v_order.user_id <> v_uid then
        raise exception 'This table already has an active order';
      end if;
      if v_role = 'customer' and v_order.id is null and v_table.status <> 'Free' then
        raise exception 'This table is unavailable';
      end if;
      if v_order.id is null then
        insert into public.orders(table_id, user_id, taken_by)
          values (v_table_id, v_uid, v_profile.username) returning * into v_order;
        update public.dining_tables set status = 'Occupied' where id = v_table_id;
      end if;
      if v_role = 'customer' and v_order.user_id <> v_uid then raise exception 'You can only change your own order'; end if;
      update public.order_items set qty = qty + v_qty
        where order_id = v_order.id and menu_id = v_menu_id and price = v_item.price;
      if not found then
        insert into public.order_items(order_id, menu_id, name, qty, price)
          values (v_order.id, v_menu_id, v_item.name, v_qty, v_item.price);
      end if;
      return jsonb_build_object('order_id', v_order.id);
    elsif v_path = '/orders/remove' then
      if v_role = 'customer' and (v_order.id is null or v_order.user_id <> v_uid) then
        raise exception 'You can only change your own order';
      end if;
      if v_order.id is not null then
        v_menu_id := (p_body ->> 'menu_id')::bigint;
        update public.order_items set qty = qty - 1 where order_id = v_order.id and menu_id = v_menu_id and qty > 1;
        if not found then
          delete from public.order_items where order_id = v_order.id and menu_id = v_menu_id and qty = 1;
        end if;
        if not exists (select 1 from public.order_items where order_id = v_order.id) then
          update public.orders set status = 'Cancelled' where id = v_order.id;
          update public.dining_tables set status = 'Free' where id = v_table_id;
        end if;
      end if;
      return jsonb_build_object('ok', true);
    else
      if v_role = 'customer' then raise exception 'Staff access required'; end if;
      if v_order.id is null then raise exception 'No open order'; end if;
      update public.orders set status = 'Cancelled' where id = v_order.id;
      update public.dining_tables set status = 'Free' where id = v_table_id;
      return jsonb_build_object('ok', true);
    end if;
  end if;

  if v_path = '/bill' then
    if v_role = 'customer' then raise exception 'Staff access required'; end if;
    v_table_id := (p_body ->> 'table_id')::bigint;
    perform pg_advisory_xact_lock(v_table_id);
    select * into v_order from public.orders where table_id = v_table_id and status = 'Open' for update;
    if not found then raise exception 'No open order for this table'; end if;
    select coalesce(sum(qty * price), 0) into v_subtotal from public.order_items where order_id = v_order.id;
    if v_subtotal <= 0 then raise exception 'Order is empty'; end if;
    v_discount_pct := coalesce(nullif(p_body ->> 'discount', '')::numeric, 0);
    if v_discount_pct not between 0 and 100 then raise exception 'Discount must be 0-100'; end if;
    v_method := coalesce(p_body ->> 'method', 'Cash');
    if v_method not in ('Cash','Card','UPI') then raise exception 'Choose Cash, Card or UPI'; end if;
    v_discount := round(v_subtotal * v_discount_pct / 100, 2);
    v_gst := round((v_subtotal - v_discount) * 0.05, 2);
    v_total := v_subtotal - v_discount + v_gst;
    insert into public.bills(order_id, subtotal, discount, gst, total, method, cashier)
      values (v_order.id, v_subtotal, v_discount, v_gst, v_total, v_method, v_profile.username)
      returning * into v_bill;
    update public.orders set status = 'Paid' where id = v_order.id;
    update public.dining_tables set status = 'Free' where id = v_table_id;
    select coalesce(jsonb_agg(jsonb_build_object('name', name, 'qty', qty, 'price', price, 'amount', round(qty * price, 2)) order by id), '[]'::jsonb)
      into v_items from public.order_items where order_id = v_order.id;
    select settings into v_settings from public.storefront where id;
    return jsonb_build_object('bill_id', v_bill.id, 'order_id', v_order.id, 'table_id', v_table_id,
      'items', v_items, 'subtotal', v_subtotal, 'discount', v_discount,
      'discount_pct', v_discount_pct, 'gst', v_gst, 'total', v_total, 'method', v_method,
      'paid_at', to_char(v_bill.paid_at, 'YYYY-MM-DD HH24:MI:SS'), 'cashier', v_profile.username,
      'gst_rate', 5, 'restaurant', v_settings ->> 'restaurant', 'address', '', 'phone', '', 'gstin', '');
  end if;

  if v_path = '/bills' then
    if v_role = 'customer' then raise exception 'Staff access required'; end if;
    v_date := nullif(split_part(v_query, '=', 2), '')::date;
    select coalesce(jsonb_agg(jsonb_build_object(
      'id', b.id, 'table_id', o.table_id, 'total', b.total, 'method', b.method,
      'paid_at', to_char(b.paid_at, 'YYYY-MM-DD HH24:MI:SS'), 'cashier', b.cashier,
      'items', coalesce((select sum(oi.qty) from public.order_items oi where oi.order_id = o.id), 0)
    ) order by b.id desc), '[]'::jsonb)
    into v_result
    from (select * from public.bills where v_date is null or paid_at::date = v_date order by id desc limit 300) b
    join public.orders o on o.id = b.order_id;
    return v_result;
  end if;

  if v_path = '/bills/detail' then
    if v_role = 'customer' then raise exception 'Staff access required'; end if;
    select * into v_bill from public.bills
      where id = split_part(v_query, '=', 2)::bigint;
    if not found then raise exception 'Bill not found'; end if;
    select * into v_order from public.orders where id = v_bill.order_id;
    select coalesce(jsonb_agg(jsonb_build_object('name', name, 'qty', qty, 'price', price, 'amount', round(qty * price, 2)) order by id), '[]'::jsonb)
      into v_items from public.order_items where order_id = v_bill.order_id;
    select settings into v_settings from public.storefront where id;
    return jsonb_build_object('bill_id', v_bill.id, 'order_id', v_bill.order_id, 'table_id', v_order.table_id,
      'items', v_items, 'subtotal', v_bill.subtotal, 'discount', v_bill.discount,
      'discount_pct', case when v_bill.subtotal > 0 then round(v_bill.discount / v_bill.subtotal * 100, 2) else 0 end,
      'gst', v_bill.gst, 'total', v_bill.total, 'method', v_bill.method,
      'paid_at', to_char(v_bill.paid_at, 'YYYY-MM-DD HH24:MI:SS'), 'cashier', v_bill.cashier,
      'gst_rate', 5, 'restaurant', v_settings ->> 'restaurant', 'address', '', 'phone', '', 'gstin', '');
  end if;

  if v_path = '/reservations' and p_body = '{}'::jsonb then
    if v_role = 'customer' then raise exception 'Staff access required'; end if;
    select coalesce(jsonb_agg(jsonb_build_object('id', r.id, 'name', r.name, 'phone', r.phone,
      'table_id', r.table_id, 'date', r.res_date, 'time', to_char(r.res_time, 'HH24:MI'),
      'guests', r.guests, 'status', r.status) order by r.res_date, r.res_time), '[]'::jsonb)
      into v_result from public.reservations r where r.status = 'Booked';
    return v_result;
  end if;

  if v_path = '/reservations' and p_body <> '{}'::jsonb then
    if v_role = 'customer' then raise exception 'Staff access required'; end if;
    v_name := btrim(coalesce(p_body ->> 'name', ''));
    v_phone := btrim(coalesce(p_body ->> 'phone', ''));
    if length(v_name) not between 1 and 60 then raise exception 'Guest name is required'; end if;
    if v_phone !~ '^[0-9+\-\s()]{7,18}$' then raise exception 'Enter a valid phone number'; end if;
    v_guests := (p_body ->> 'guests')::integer;
    if v_guests not between 1 and 50 then raise exception 'Guests must be between 1 and 50'; end if;
    v_date := (p_body ->> 'date')::date;
    v_time := (p_body ->> 'time')::time;
    if (v_date + v_time) <= now() then raise exception 'Choose a future date and time'; end if;
    select t.id into v_table_id from public.dining_tables t
      where t.seats >= v_guests and not exists (
        select 1 from public.reservations r where r.table_id = t.id and r.res_date = v_date and r.res_time = v_time and r.status = 'Booked'
      ) order by t.seats, t.id limit 1 for update;
    if not found then raise exception 'No table available for that slot'; end if;
    insert into public.reservations(name, phone, table_id, res_date, res_time, guests)
      values (v_name, v_phone, v_table_id, v_date, v_time, v_guests) returning * into v_res;
    return jsonb_build_object('id', v_res.id, 'table_id', v_res.table_id);
  end if;

  if v_path = '/reservations/cancel' then
    if v_role = 'customer' then raise exception 'Staff access required'; end if;
    update public.reservations set status = 'Cancelled' where id = (p_body ->> 'id')::bigint and status = 'Booked';
    return jsonb_build_object('ok', true);
  end if;

  if v_path = '/users' then
    if v_role <> 'admin' then raise exception 'Admin access required'; end if;
    select coalesce(jsonb_agg(jsonb_build_object('username', username, 'role', role, 'email', email)
      order by role, username), '[]'::jsonb)
      into v_result from public.profiles where not is_anonymous;
    return v_result;
  end if;

  if v_path in ('/users/add','/users/delete') then
    if v_role <> 'admin' then raise exception 'Admin access required'; end if;
    raise exception 'Manage staff accounts in Supabase Authentication. Assign roles in public.profiles; never share an admin key with the browser.';
  end if;

  if v_path = '/report' then
    if v_role <> 'admin' then raise exception 'Admin access required'; end if;
    return jsonb_build_object(
      'today', (select jsonb_build_object(
        'bills', count(*), 'sales', coalesce(sum(subtotal),0), 'gst', coalesce(sum(gst),0),
        'collected', coalesce(sum(total),0), 'discount', coalesce(sum(discount),0),
        'items', coalesce((select sum(oi.qty) from public.order_items oi join public.bills bb on bb.order_id = oi.order_id where bb.paid_at::date = current_date),0)
      ) from public.bills where paid_at::date = current_date),
      'top', coalesce((select jsonb_agg(jsonb_build_object('name', s.name, 'qty', s.qty, 'revenue', s.revenue) order by s.qty desc)
        from (select oi.name, sum(oi.qty)::integer qty, sum(oi.qty * oi.price)::numeric revenue
          from public.order_items oi join public.bills b on b.order_id = oi.order_id
          group by oi.name order by sum(oi.qty) desc limit 5) s), '[]'::jsonb),
      'methods', coalesce((select jsonb_agg(jsonb_build_object('method', method, 'bills', bills, 'total', total) order by method)
        from (select method, count(*)::integer bills, sum(total)::numeric total from public.bills group by method) s), '[]'::jsonb),
      'days', coalesce((select jsonb_agg(jsonb_build_object('date', day, 'bills', bills, 'total', total) order by day desc)
        from (select paid_at::date day, count(*)::integer bills, sum(total)::numeric total from public.bills
          group by paid_at::date order by paid_at::date desc limit 7) s), '[]'::jsonb)
    );
  end if;

  if v_path = '/export/bills' then
    if v_role <> 'admin' then raise exception 'Admin access required'; end if;
    v_csv := '"Bill ID","Order ID","Table","Paid at","Subtotal","Discount","GST","Total","Method","Cashier"' || E'\r\n';
    for v_row in
      select b.id, b.order_id, o.table_id, to_char(b.paid_at, 'YYYY-MM-DD HH24:MI:SS') paid_at,
        b.subtotal, b.discount, b.gst, b.total, b.method, b.cashier
      from public.bills b join public.orders o on o.id = b.order_id order by b.id
    loop
      v_csv := v_csv || format('"%s","%s","%s","%s","%s","%s","%s","%s","%s","%s"',
        v_row.id, v_row.order_id, v_row.table_id, v_row.paid_at, v_row.subtotal,
        v_row.discount, v_row.gst, v_row.total, replace(v_row.method, '"', '""'),
        replace(v_row.cashier, '"', '""')) || E'\r\n';
    end loop;
    return to_jsonb(chr(65279) || v_csv);
  end if;

  raise exception 'Not found';
end;
$$;

