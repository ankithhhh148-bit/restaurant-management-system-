create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  username text not null,
  role text not null default 'customer' check (role in ('admin', 'staff', 'customer')),
  is_anonymous boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.menu (
  id bigint generated by default as identity primary key,
  name text not null unique check (length(btrim(name)) between 1 and 60),
  category text not null check (length(btrim(category)) between 1 and 30),
  price numeric(10,2) not null check (price > 0 and price <= 100000),
  available boolean not null default true
);

create table if not exists public.dining_tables (
  id bigint generated by default as identity primary key,
  seats integer not null check (seats between 1 and 30),
  status text not null default 'Free' check (status in ('Free', 'Occupied'))
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  table_id bigint not null references public.dining_tables(id),
  status text not null default 'Open' check (status in ('Open', 'Paid', 'Cancelled')),
  created_at timestamptz not null default now(),
  user_id uuid not null references public.profiles(id),
  taken_by text not null
);

create unique index if not exists one_open_order_per_table
  on public.orders(table_id) where status = 'Open';

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete restrict,
  menu_id bigint not null references public.menu(id) on delete restrict,
  name text not null,
  qty integer not null check (qty > 0),
  price numeric(10,2) not null check (price > 0)
);

create table if not exists public.bills (
  id bigint generated by default as identity primary key,
  order_id bigint not null unique references public.orders(id),
  subtotal numeric(12,2) not null,
  discount numeric(12,2) not null default 0,
  gst numeric(12,2) not null,
  total numeric(12,2) not null,
  method text not null check (method in ('Cash', 'Card', 'UPI')),
  paid_at timestamptz not null default now(),
  cashier text not null
);

create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  name text not null check (length(btrim(name)) between 1 and 60),
  phone text not null check (length(phone) between 7 and 18),
  table_id bigint not null references public.dining_tables(id),
  res_date date not null,
  res_time time not null,
  guests integer not null check (guests between 1 and 50),
  status text not null default 'Booked' check (status in ('Booked', 'Cancelled'))
);

create unique index if not exists one_booking_per_table_slot
  on public.reservations(table_id, res_date, res_time) where status = 'Booked';

create table if not exists public.storefront (
