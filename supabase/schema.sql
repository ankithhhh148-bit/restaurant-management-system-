create or replace function public.rms_create_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles(id, email, username, role, is_anonymous)
  values (
    new.id,
    coalesce(new.email, new.id::text || '@anonymous.invalid'),
    coalesce(nullif(new.raw_user_meta_data ->> 'username', ''), split_part(coalesce(new.email, 'Guest'), '@', 1)),
    'customer',
    new.is_anonymous
  )
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists rms_auth_user_created on auth.users;
create trigger rms_auth_user_created
  after insert on auth.users
  for each row execute function public.rms_create_profile();

insert into public.profiles(id, email, username, role, is_anonymous)
select
  u.id,
  coalesce(u.email, u.id::text || '@anonymous.invalid'),
  coalesce(nullif(u.raw_user_meta_data ->> 'username', ''), split_part(coalesce(u.email, 'Guest'), '@', 1)),
  'customer',
  u.is_anonymous
from auth.users u
on conflict (id) do nothing;

